"""NFR-REL-03: migrations apply on an empty database and match the models."""

import asyncio
import re
import secrets
from collections.abc import Iterator

import pytest
from alembic import command
from alembic.config import Config
from sqlalchemy import make_url, text
from sqlalchemy.ext.asyncio import create_async_engine

from tests.migrations.alembic_config import BACKEND_DIR, alembic_config

REVISION_FILE = re.compile(r"\d{8}_\d{4}_[a-z0-9_]+\.py")


async def _execute_autocommit(url: str, *statements: str) -> list[object]:
    engine = create_async_engine(url, isolation_level="AUTOCOMMIT")
    results: list[object] = []
    async with engine.connect() as connection:
        for statement in statements:
            result = await connection.execute(text(statement))
            results.append(result.scalar() if result.returns_rows else None)
    await engine.dispose()
    return results


@pytest.fixture
def empty_database_url(database_url: str) -> Iterator[str]:
    """A brand-new database next to the shared test database."""
    name = f"migrations_{secrets.token_hex(4)}"
    asyncio.run(_execute_autocommit(database_url, f'CREATE DATABASE "{name}"'))
    url = make_url(database_url).set(database=name).render_as_string(hide_password=False)
    yield url
    asyncio.run(_execute_autocommit(database_url, f'DROP DATABASE "{name}" WITH (FORCE)'))


@pytest.fixture
def config(empty_database_url: str) -> Config:
    return alembic_config(empty_database_url)


def test_upgrade_head_on_empty_database(config: Config, empty_database_url: str) -> None:
    command.upgrade(config, "head")

    version, extension = asyncio.run(
        _execute_autocommit(
            empty_database_url,
            "SELECT version_num FROM alembic_version",
            "SELECT extname FROM pg_extension WHERE extname = 'pg_trgm'",
        )
    )
    assert version is not None
    assert extension == "pg_trgm"


def test_models_and_migrations_have_no_drift(config: Config) -> None:
    command.upgrade(config, "head")

    command.check(config)  # raises AutogenerateDiffsDetected on drift


@pytest.mark.parametrize(
    ("expression", "expected"),
    [
        ("zk_search_norm('Ёжик')", "ежик"),
        ("zk_search_fold('Малако')", "малака"),
        ("zk_search_fold('Молоко') = zk_search_fold('малако')", True),
        (
            "word_similarity(zk_search_fold('макорон'), zk_search_fold('макароны паста')) >= 0.5",
            True,
        ),
    ],
    ids=["norm-yo", "fold-vowels", "typo-equal", "fuzzy-word-similarity"],
)
def test_search_functions_from_baseline(
    config: Config, empty_database_url: str, expression: str, expected: object
) -> None:
    command.upgrade(config, "head")

    (value,) = asyncio.run(_execute_autocommit(empty_database_url, f"SELECT {expression}"))

    assert value == expected


def test_revision_files_follow_naming_rule() -> None:
    files = [p.name for p in (BACKEND_DIR / "alembic" / "versions").glob("*.py")]

    assert files
    assert all(REVISION_FILE.fullmatch(name) for name in files), files


def test_alembic_ini_has_no_database_url() -> None:
    ini = (BACKEND_DIR / "alembic.ini").read_text(encoding="utf-8")

    assert not re.search(r"^\s*sqlalchemy\.url\s*=", ini, re.MULTILINE)
