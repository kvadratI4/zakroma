"""Create deploy/.env for the prod stack with random database passwords (T-007).

Standard library only, so it also runs on the server without uv:
    python3 backend/scripts/init_prod_env.py --site-address zakroma.example.ru
Local run of the prod build (https://127.0.0.1:8443):
    uv run python scripts/init_prod_env.py --site-address 127.0.0.1
The file is git-ignored and created with mode 0600; an existing file is never overwritten and
the passwords are never printed.
"""

import argparse
import os
import re
import secrets
import sys
from pathlib import Path

DEFAULT_PATH = Path(__file__).resolve().parents[2] / "deploy" / ".env"
PASSWORD_VARS = ("POSTGRES_PASSWORD", "ZAKROMA_OWNER_PASSWORD", "ZAKROMA_APP_PASSWORD")
LOCAL_SITE = "127.0.0.1"
# Host name or IPv4 only: the value goes into the env file and the Caddy site address.
_SITE_ADDRESS = re.compile(r"(?=.{1,253}\Z)[A-Za-z0-9](?:[A-Za-z0-9.-]*[A-Za-z0-9])?\Z")


def render_env(site_address: str) -> str:
    if not _SITE_ADDRESS.match(site_address):
        raise ValueError("site address must be a host name or an IPv4 address, without a port")
    lines = [
        "# Prod stack secrets. Generated by backend/scripts/init_prod_env.py; never commit.",
        *(f"{name}={secrets.token_urlsafe(32)}" for name in PASSWORD_VARS),
        f"SITE_ADDRESS={site_address}",
    ]
    if site_address == LOCAL_SITE:
        # Local run: Caddy listens on loopback only, away from ports other programs use.
        lines += ["HTTP_BIND=127.0.0.1:8080", "HTTPS_BIND=127.0.0.1:8443"]
    return "\n".join(lines) + "\n"


def write_prod_env(path: Path, site_address: str) -> bool:
    """Write the env file; return False if it already exists."""
    content = render_env(site_address)
    if path.exists():
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    # Created with 0600 at once: there is no moment when the file is readable by others.
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as file:
        file.write(content)
    return True


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Create deploy/.env for the prod stack.")
    parser.add_argument("--site-address", required=True, help="domain, or 127.0.0.1 locally")
    parser.add_argument("--output", type=Path, default=DEFAULT_PATH)
    args = parser.parse_args(argv)
    output: Path = args.output
    try:
        created = write_prod_env(output, args.site_address)
    except ValueError as error:
        print(f"Invalid {error}", file=sys.stderr)
        return 2
    print(f"Created {output}" if created else f"{output} already exists, left unchanged")
    return 0


if __name__ == "__main__":
    sys.exit(main())
