"""Create deploy/.env.dev with a random local database password.

Run once per clone:  uv run python scripts/init_dev_env.py
The file is git-ignored; an existing file is never overwritten and the password is never printed.
"""

import secrets
from pathlib import Path

DEFAULT_PATH = Path(__file__).resolve().parents[2] / "deploy" / ".env.dev"
DB_USER = "zakroma"
DB_NAME = "zakroma"


def write_dev_env(path: Path) -> bool:
    """Write the env file; return False if it already exists."""
    if path.exists():
        return False
    password = secrets.token_urlsafe(32)
    content = "\n".join(
        [
            "# Local development only. Generated by backend/scripts/init_dev_env.py; never commit.",
            f"POSTGRES_USER={DB_USER}",
            f"POSTGRES_DB={DB_NAME}",
            f"POSTGRES_PASSWORD={password}",
            f"DATABASE_URL=postgresql+asyncpg://{DB_USER}:{password}@127.0.0.1:5432/{DB_NAME}",
            "",
        ]
    )
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("x", encoding="utf-8", newline="\n") as file:
        file.write(content)
    path.chmod(0o600)
    return True


def main() -> None:
    if write_dev_env(DEFAULT_PATH):
        print(f"Created {DEFAULT_PATH}")
    else:
        print(f"{DEFAULT_PATH} already exists, left unchanged")


if __name__ == "__main__":
    main()
